/** 建立圖示元素（內容是上面寫死的常數，不含使用者輸入） */
export function icon(name) {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', 'icon');
  svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = ICONS[name] || ICONS.file;
  return svg;
}

/** 把 HTML 裡標了 data-icon 的元素補上圖示（圖示放在文字前面） */
export function hydrateIcons() {
  document.querySelectorAll('[data-icon]').forEach((el) => {
    if (!el.querySelector(':scope > svg.icon')) el.prepend(icon(el.dataset.icon));
  });
}

/** 依檔案類型挑圖示 */
export function fileIcon(mime, name) {
  const ext = (name || '').split('.').pop().toLowerCase();
  if ((mime || '').startsWith('image/')) return 'image';
  if ((mime || '').startsWith('video/')) return 'video';
  if ((mime || '').startsWith('audio/')) return 'audio';
  if (/^(zip|rar|7z|tar|gz|tgz)$/.test(ext)) return 'archive';
  if (mime === 'application/pdf' || /^(pdf|doc|docx|odt|rtf|txt|md)$/.test(ext)) return 'doc';
  if (/^(xls|xlsx|csv|ods)$/.test(ext)) return 'sheet';
  if (/^(ppt|pptx|key|odp)$/.test(ext)) return 'slides';
  return 'file';
}

